package ru.akhcheck.patterns.command.commands;

/**
 * Запрос, ставший объектом.
 *
 * <p>Ровно в этом смысл паттерна. Раз запрос это объект, его можно положить в
 * список, передать другому, выполнить позже, повторить и сложить в историю.
 * Прямой вызов метода ничего из перечисленного не умеет.
 */
public interface Command {
    void execute();

    int getPrice();
}

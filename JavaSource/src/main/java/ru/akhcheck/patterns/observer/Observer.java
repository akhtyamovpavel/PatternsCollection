package ru.akhcheck.patterns.observer;

/**
 * Тот, кого уведомляют об изменении.
 *
 * <p>Наблюдатель ничего не спрашивает сам. Источник сообщает ему, что
 * произошло, и потому источник не зависит от того, сколько подписчиков и что
 * именно они делают.
 */
public interface Observer {
    void update(String message);
}

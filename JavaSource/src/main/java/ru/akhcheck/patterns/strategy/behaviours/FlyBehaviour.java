package ru.akhcheck.patterns.strategy.behaviours;

/**
 * Одна ось поведения утки, вынесенная из самой утки.
 *
 * <p>Смысл стратегии в том, что поведение хранится рядом, а не наследуется.
 * Утка одна, а летать, крякать и плавать она может по-разному, и сочетания
 * собираются во время работы, а не при написании кода.
 */
public interface FlyBehaviour {
    void execute();
}
